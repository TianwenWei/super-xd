def canonical(value):
    def normalize(item):
        if isinstance(item,float) and item.is_integer(): return int(item)
        if isinstance(item,dict): return {k:normalize(v) for k,v in item.items()}
        if isinstance(item,list): return [normalize(v) for v in item]
        return item
    return json.dumps(normalize(value),ensure_ascii=False,sort_keys=True,separators=(',',':'))


def flatten(value, prefix=''):
    if isinstance(value,dict) and value:
        return {path:item for key,child in value.items() for path,item in flatten(child,f'{prefix}.{key}' if prefix else key).items()}
    return {prefix:value}


def changed_paths(before, after):
    a,b=flatten(before),flatten(after)
    return sorted(k for k in a.keys()|b.keys() if canonical(a.get(k,{'missing':True}))!=canonical(b.get(k,{'missing':True})))


def path_allowed(path, allowed):
    return any(path==item or (item.endswith('.*') and path.startswith(item[:-1])) for item in allowed)


def chinese_number(text):
    negative=text.startswith('负'); text=text.removeprefix('负')
    whole,_,fraction=text.partition('点'); digits={c:i for i,c in enumerate('零一二三四五六七八九')};digits.update({'两':2,'〇':0})
