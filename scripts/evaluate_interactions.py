def action(name, **arguments):
    return {'name': name, 'arguments': arguments}


def step(id, query, *, actions=(), loads=(), target=None, changed=(), kind='control', **extra):
    return {'id': id, 'query': query, 'kind': kind, 'actions': list(actions),
            'loads': list(loads), 'target_state': target or {}, 'allowed_changed_paths': list(changed), **extra}


def temperature(id, query, value, zone='all'):
    zones = ['driver', 'front_passenger', 'rear'] if zone == 'all' else [zone]
    targets = {f'climate.temperatures.{z}': value for z in zones} | {'climate.power': True}
    return step(id, query, actions=[action('set_temperature', zone=zone, temperature=value)],
                target=targets, changed=targets)


def window(id, query, value, seat='driver'):
    path = f'windows.positions.{seat}'
    return step(id, query, actions=[action('set_window_position', window=seat, position=value)],
                target={path: value}, changed=[path])


def volume(id, query, value):
    return step(id, query, actions=[action('set_volume', volume=value)],
                target={'media.volume': value}, changed=['media.volume'])


def massage(id, query, mode='relax', seat='driver'):
    path = f'seats.positions.{seat}.massage'
    return step(id, query, actions=[action('set_seat_massage', seat=seat, mode=mode)], loads=['seats'],
                target={path: mode}, changed=[path])


def chat(id, query, **extra):
    return step(id, query, kind='chat', **extra)


def state_question(id, query, claims):
    return step(id, query, kind='state', claims=claims)


def delegate(id, query, alias, facts, mode='research', **extra):
    return step(id, query, kind='delegate', assign_task=alias, goal_facts=facts,
                query_mode=mode, **extra)


def task_operation(id, query, operations, **extra):
    return step(id, query, kind='task', task_operations=operations, **extra)


